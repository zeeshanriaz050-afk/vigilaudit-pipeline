import React, { useState } from 'react';
import { X, Download, Copy, Check, FileText, CheckCircle2 } from 'lucide-react';
import { AuditReport } from '../types/audit';

interface ExportModalProps {
  report: AuditReport | null;
  onClose: () => void;
}

export const ExportModal: React.FC<ExportModalProps> = ({ report, onClose }) => {
  const [copiedFormat, setCopiedFormat] = useState<string | null>(null);

  if (!report) return null;

  const generateMarkdownReport = (): string => {
    const { summary, stage1_static_ast, stage2_security_vulnerabilities, stage3_quality_refactoring } = report;

    return `# 🛡️ VigilAudit Autonomous Security & Quality Audit Report
**Date:** ${new Date().toUTCString()}  
**Target:** Production Codebase  
**Project Health Score:** ${summary.projectHealthScore}/100  
**Security Score:** ${summary.securityScore}/100 | **Maintainability:** ${summary.maintainabilityScore}/100 | **Documentation:** ${summary.documentationScore}/100  

---

## 📌 Executive Summary
${summary.executiveSummary}

- **Critical Vulnerabilities:** ${summary.criticalCount}
- **High Vulnerabilities:** ${summary.highCount}
- **Medium Vulnerabilities:** ${summary.mediumCount}
- **Low / Code Smells:** ${summary.lowCount}

---

## 🚨 Security Vulnerabilities (Stage 2)
${
  stage2_security_vulnerabilities?.findings?.length
    ? stage2_security_vulnerabilities.findings
        .map(
          (f) => `### [${f.severity}] ${f.title} (${f.cwe || 'CWE'})
- **File:** \`${f.file}:${f.line}\`
- **CVSS:** ${f.cvss || 'N/A'}
- **Category:** ${f.category}
- **Impact:** ${f.impact}
- **Recommendation:** ${f.recommendation}

\`\`\`
${f.problematicCode || ''}
\`\`\`
`
        )
        .join('\n')
    : 'No severe security vulnerabilities detected.'
}

---

## 🔑 Hardcoded Secrets & Credentials
${
  stage2_security_vulnerabilities?.secretsDetected?.length
    ? stage2_security_vulnerabilities.secretsDetected
        .map((s) => `- **${s.type}**: \`${s.maskedValue}\` in \`${s.file}:${s.line}\` (Risk: ${s.risk})`)
        .join('\n')
    : 'No hardcoded secrets detected.'
}

---

## ⚙️ Static AST & Complexity (Stage 1)
- **Cyclomatic Complexity:** ${stage1_static_ast?.metrics?.cyclomaticComplexity || 'Optimal'}
- **Maintainability Index:** ${stage1_static_ast?.metrics?.maintainabilityIndex || 85}/100
- **Testability Grade:** ${stage1_static_ast?.metrics?.testabilityGrade || 'A'}
- **Smells Detected:** ${stage1_static_ast?.smells?.length || 0}

---

## 🔄 Quality & Refactoring Summary (Stage 3)
${stage3_quality_refactoring?.overallImprovementSummary || 'Standard refactoring diffs generated.'}
**Estimated Impact:** ${stage3_quality_refactoring?.estimatedSpeedupOrSafetyGain || 'Performance and security hardened'}

---
*Report autonomously generated by VigilAudit Pipeline v2.4 powered by Google Gemini 3.8 Flash.*
`;
  };

  const handleDownloadMarkdown = () => {
    const md = generateMarkdownReport();
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `vigil-audit-report-${Date.now()}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadJson = () => {
    const jsonStr = JSON.stringify(report, null, 2);
    const blob = new Blob([jsonStr], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `vigil-audit-report-${Date.now()}.json`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(generateMarkdownReport());
    setCopiedFormat('md');
    setTimeout(() => setCopiedFormat(null), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/80 p-4 backdrop-blur-sm">
      <div className="relative flex w-full max-w-xl flex-col rounded-2xl border border-slate-700 bg-slate-900 shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-slate-800 bg-slate-950 px-6 py-4">
          <div className="flex items-center gap-2.5">
            <Download className="h-5 w-5 text-cyan-400" />
            <h3 className="text-base font-bold text-white">Export Autonomous Audit Report</h3>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg p-2 text-slate-400 hover:bg-slate-800 hover:text-white transition-colors"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 space-y-4 text-xs text-slate-300">
          <p>
            Choose your preferred export format for documentation, compliance submission, or attaching to a GitHub Pull Request.
          </p>

          <div className="space-y-3">
            {/* Markdown option */}
            <div className="rounded-xl border border-slate-800 bg-slate-950 p-4 flex items-center justify-between gap-4">
              <div>
                <h4 className="text-sm font-bold text-white flex items-center gap-2">
                  <FileText className="h-4 w-4 text-cyan-400" />
                  Markdown Report (.md)
                </h4>
                <p className="text-slate-400 text-[11px] mt-0.5">
                  Formatted for GitHub PR comments, issue trackers, and project documentation.
                </p>
              </div>
              <div className="flex items-center gap-2 shrink-0">
                <button
                  onClick={handleCopyMarkdown}
                  className="rounded-lg border border-slate-800 bg-slate-900 px-3 py-1.5 text-xs text-slate-300 hover:bg-slate-800 transition-colors flex items-center gap-1"
                >
                  {copiedFormat === 'md' ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
                  <span>{copiedFormat === 'md' ? 'Copied' : 'Copy'}</span>
                </button>
                <button
                  onClick={handleDownloadMarkdown}
                  className="rounded-lg bg-cyan-500 px-3 py-1.5 text-xs font-semibold text-slate-950 hover:bg-cyan-400 transition-colors flex items-center gap-1"
                >
                  <Download className="h-3.5 w-3.5" />
                  <span>Download</span>
                </button>
              </div>
            </div>

            {/* JSON option */}
            <div className="rounded-xl border border-slate-800 bg-slate-950 p-4 flex items-center justify-between gap-4">
              <div>
                <h4 className="text-sm font-bold text-white flex items-center gap-2">
                  <FileText className="h-4 w-4 text-emerald-400" />
                  Machine-Readable JSON Artifact
                </h4>
                <p className="text-slate-400 text-[11px] mt-0.5">
                  Complete structured schema for SIEM, SonarQube, or custom CI/CD parsing.
                </p>
              </div>
              <div className="shrink-0">
                <button
                  onClick={handleDownloadJson}
                  className="rounded-lg bg-emerald-500 px-3 py-1.5 text-xs font-semibold text-slate-950 hover:bg-emerald-400 transition-colors flex items-center gap-1"
                >
                  <Download className="h-3.5 w-3.5" />
                  <span>Download JSON</span>
                </button>
              </div>
            </div>
          </div>
        </div>

        {/* Footer */}
        <div className="border-t border-slate-800 bg-slate-950/80 px-6 py-3 flex justify-end">
          <button
            onClick={onClose}
            className="rounded-lg bg-slate-800 px-4 py-1.5 text-xs font-medium text-white hover:bg-slate-700 transition-colors"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
};
